const NUMERIC = { height: [80, 250], weight: [20, 300], chest: [50, 200], waist: [40, 200], hips: [50, 200] };
function cleanNum(key, v) {
  const n = Math.round(Number(v));
  const [lo, hi] = NUMERIC[key];
  return v !== "" && v != null && n >= lo && n <= hi ? String(n) : "";
}

