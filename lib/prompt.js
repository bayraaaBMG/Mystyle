function storableInput(raw) {
  const a = { ...raw };
  Object.keys(NUMERIC).forEach((k) => { a[k] = cleanNum(k, a[k]); });
  const keep = ["gender", "height", "weight", "chest", "waist", "hips", "body", "face", "skin", "undertone", "style", "occasion", "season"];
  const out = {};
  keep.forEach((k) => { if (a[k] !== undefined && a[k] !== null && a[k] !== "") out[k] = String(a[k]).slice(0, 100); });
  return out;
}

